const orderedPhrases = Object.entries(phrases).sort(([a], [b]) => b.length - a.length);
const translatableAttributes = ["placeholder", "aria-label", "title", "alt"];
const nodeState = new WeakMap();
const attributeState = new WeakMap();

function translate(text) {
  const trimmed = text.trim();
  if (!trimmed) return text;
  if (phrases[trimmed]) return text.replace(trimmed, phrases[trimmed]);
  let result = trimmed;
  for (const [source, target] of orderedPhrases) {
    if (source.length > 2 && result.includes(source)) result = result.split(source).join(target);
  }
  return text.replace(trimmed, result);
}

function updateTracked(target, current, locale, setter, store) {
  let tracked = store.get(target);
  if (!tracked) {
    tracked = { source: current, output: current };
    store.set(target, tracked);
  } else if (current !== tracked.output) {
    // React or the application changed the value since the last localization pass.
    tracked.source = current;
  }
  const next = locale === "en" ? translate(tracked.source) : tracked.source;
  if (next !== current) setter(next);
  tracked.output = next;
}

function localizeDocument(locale) {
  if (!document.body) return;
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  let node;
  while ((node = walker.nextNode())) {
    if (["SCRIPT", "STYLE", "NOSCRIPT"].includes(node.parentElement?.tagName)) continue;
    if (node.parentElement?.closest('[translate="no"]')) continue;
    updateTracked(node, node.nodeValue, locale, (value) => { node.nodeValue = value; }, nodeState);
  }
  document.body.querySelectorAll("*").forEach((element) => {
    if (element.closest('[translate="no"]')) return;
    for (const name of translatableAttributes) {
      if (!element.hasAttribute(name)) continue;
      let tracked = attributeState.get(element);
      if (!tracked) {
        tracked = new Map();
        attributeState.set(element, tracked);
      }
      let value = tracked.get(name);
      const current = element.getAttribute(name);
      if (!value) value = { source: current, output: current };
      else if (current !== value.output) value.source = current;
      const next = locale === "en" ? translate(value.source) : value.source;
      if (next !== current) element.setAttribute(name, next);
      value.output = next;
      tracked.set(name, value);
    }
  });
}

export default function DocumentTranslator() {
  useEffect(() => {
    let observer;
    let frame = 0;
    const apply = () => {
      if (frame) cancelAnimationFrame(frame);
      frame = requestAnimationFrame(() => {
        frame = 0;
        observer?.disconnect();
        localizeDocument(document.documentElement.lang);
        observer?.observe(document.documentElement, {
          subtree: true,
          childList: true,
          characterData: true,
          attributes: true,
          attributeFilter: ["lang", ...translatableAttributes],
        });
      });
    };
    observer = new MutationObserver(apply);
    apply();
    return () => {
      if (frame) cancelAnimationFrame(frame);
      observer.disconnect();
    };
  }, []);
  return null;
}
