CREATE TABLE shop_payments (
    payment_id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    order_id BIGINT NOT NULL,
    reference VARCHAR(50) NOT NULL,
    method VARCHAR(30) NOT NULL,
    amount DECIMAL(15,2) NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'UNPAID',
    checkout_url TEXT NULL,
    bank_name VARCHAR(100) NULL,
    bank_id VARCHAR(30) NULL,
    account_number VARCHAR(30) NULL,
    account_name VARCHAR(100) NULL,
    external_key VARCHAR(200) NULL,
    refund_key VARCHAR(200) NULL,
    expires_at DATETIME(6) NULL,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    CONSTRAINT uk_shop_payment_order UNIQUE (order_id),
    CONSTRAINT uk_shop_payment_reference UNIQUE (reference),
    CONSTRAINT uk_shop_payment_external UNIQUE (external_key),
    CONSTRAINT uk_shop_payment_refund UNIQUE (refund_key),
    CONSTRAINT fk_shop_payment_order FOREIGN KEY (order_id) REFERENCES orders(order_id),
    CONSTRAINT ck_shop_payment_amount CHECK (amount > 0),
    CONSTRAINT ck_shop_payment_method CHECK (method IN ('BANK_TRANSFER','VIETQR','VNPAY','ZALOPAY','MOMO')),
    CONSTRAINT ck_shop_payment_status CHECK (status IN ('UNPAID','PAID','FAILED','REFUND_PENDING','REFUNDED'))
);
